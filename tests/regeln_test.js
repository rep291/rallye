// V3-Regeln: Finanzpolizei (6 = frei + sofort noch einmal würfeln), ZIEL nur mit exakter Zahl, Feld 100 = Frage, Rutsche 99 -> 87
// Start: FAST=1 TEST_HOOKS=1 NO_SAVE=1 PORT=3750 node server.js & node tests/regeln_test.js
const { io } = require('socket.io-client');
const URL = process.env.URL || 'http://localhost:3750';
const sleep = ms => new Promise(r => setTimeout(r, ms));
const ok = (c, m) => { if (!c) throw new Error('FEHLER: ' + m + ' | Log: ' + (H.S ? H.S.log.slice(0, 4).map(l => l.msg).join(' / ') : '')); console.log('  ✔ ' + m); };
const ask = (c, ev, ...a) => new Promise(r => c.emit(ev, ...a, r));
const H = { S: null };
(async () => {
  const board = (await (await fetch(URL + '/api/config')).json()).board, F = board.fields, LAST = F.length - 1;
  ok(F[100].type === 'frage', 'Feld 100 (letztes vor dem ZIEL) ist ein Fragefeld');
  ok(F[99].type === 'rutsche' && F[99].to === 87, 'Feld 99 ist Rutsche auf 87');
  ok(board.rules.finishExact === true && board.rules.finanzpolizei.afterRelease === 'rollAgain', 'Standard: exaktes Ziel, Finanzpolizei = noch einmal würfeln');
  const h = io(URL, { forceNew: true }); H.c = h; H.seen = []; h.on('state', s => { H.S = s; if (s.pending && s.pending.type === 'info') H.seen.push(s.pending); }); await new Promise(r => h.on('connect', r));
  const op = await ask(h, 'host:open', {}); const code = op.code;
  const mk = async name => { const c = io(URL, { forceNew: true }); const P = { c, S: null }; c.on('state', s => P.S = s); await new Promise(r => c.on('connect', r)); const r = await ask(c, 'join', { name, room: code }); P.id = r.id; return P; };
  const A = await mk('Anna'), B = await mk('Ben');
  h.emit('host:start'); await sleep(150);
  const me = id => H.S.players.find(p => p.id === id);
  const idle = async (ms = 5000) => { const t = Date.now(); while (!(H.S.phase !== 'playing' || (!H.S.pending && !H.S.busy))) { if (Date.now() - t > ms) throw new Error('Timeout'); await sleep(20); } };
  const turnTo = async P => { await idle(); if (H.S.players[H.S.turn].id !== P.id) { h.emit('host:skipTurn'); await sleep(80); await idle(); } ok(H.S.players[H.S.turn].id === P.id, 'Zug bei ' + me(P.id).name); };
  const roll = async (P, ...dice) => { h.emit('test:dice', dice); await sleep(40); P.c.emit('roll'); await sleep(60); };
  ok(H.S.finishExact === true && H.S.room.settings.finishExact == null, 'Einstellung „exakte Zahl“ ist standardmäßig an');
  console.log('1) Finanzpolizei');
  await turnTo(A); h.emit('test:setPos', A.id, 33, true); await sleep(60);
  await roll(A, 4); await idle(); ok(me(A.id).jail && me(A.id).pos === 33 && H.S.players[H.S.turn].id === B.id, 'ohne 6: bleibt sitzen, Ben ist dran');
  await turnTo(A); H.seen = []; await roll(A, 6);
  const t0 = Date.now(); while (!H.seen.some(x => x.kind === 'frei') && Date.now() - t0 < 3000) await sleep(20);
  ok(H.seen.some(x => x.kind === 'frei' && /noch einmal würfeln/.test(x.text)), 'Meldung: frei, noch einmal würfeln');
  ok(me(A.id).pos === 33 && !me(A.id).jail, 'bei der 6 frei, aber NICHT 6 Felder gezogen');
  await idle(); ok(H.S.players[H.S.turn].id === A.id && me(A.id).again, 'Anna würfelt sofort noch einmal (Handy: „Noch einmal würfeln!“)');
  await roll(A, 3); await idle(); ok(me(A.id).pos === 36 && H.S.players[H.S.turn].id === B.id, 'zieht mit dem neuen Wurf (3) auf 36, dann Ben');
  ok(H.S.log.some(l => /frei! Jetzt noch einmal würfeln/.test(l.msg)), 'Log-Eintrag Finanzpolizei');
  console.log('2) ZIEL nur mit exakter Zahl');
  await turnTo(A); h.emit('test:setPos', A.id, 98, false); await sleep(60);
  H.seen = []; await roll(A, 5); await idle();
  ok(H.seen.some(x => x.kind === 'zuhoch' && /genau 3/.test(x.text)), 'Hinweis aufs Handy/Beamer: Typ „zuhoch“');
  ok(me(A.id).pos === 98 && H.S.phase === 'playing', 'Wurf 5 auf Feld 98 (braucht 3): bleibt stehen, kein Zurückprallen');
  ok(H.S.log.some(l => /zu viel! Fürs ZIEL braucht es genau 3/.test(l.msg)), 'klare Meldung „zu viel … genau 3“');
  await turnTo(A); await roll(A, 2);
  let t1 = Date.now(); while (!(H.S.pending && H.S.pending.type === 'question') && Date.now() - t1 < 3000) await sleep(20);
  ok(me(A.id).pos === 100 && H.S.pending && H.S.pending.type === 'question', 'Feld 100: Fragekarte');
  h.emit('host:judge', 5); await idle();
  ok(me(A.id).pos === 100 && H.S.log.some(l => /über das ZIEL hinaus/.test(l.msg)), 'Bewertung +5 auf Feld 100: bleibt stehen (genau 1 nötig)');
  await turnTo(B); h.emit('test:setPos', B.id, 97, false); await sleep(60); H.seen = []; await roll(B, 2);
  t1 = Date.now(); while (!H.seen.some(x => x.kind === 'rutsche') && Date.now() - t1 < 3000) await sleep(20);
  ok(H.seen.some(x => x.kind === 'rutsche' && /99 auf Feld 87/.test(x.text)), 'Feld 99: Rutsche angekündigt (99 → 87)');
  await idle(); ok(me(B.id).pos === 87, 'Ben rutscht von 99 auf 87');
  await turnTo(A); await roll(A, 1); await idle(); ok(H.S.phase === 'finished' && H.S.winner.playerId === A.id, 'genau 1 von Feld 100 → ZIEL, Sieg');
  console.log('3) Exakt-Regel abschaltbar');
  h.emit('host:reset', true); await sleep(100); h.emit('host:settings', { finishExact: false }); await sleep(60); h.emit('host:start'); await sleep(120);
  ok(H.S.finishExact === false, 'Einstellung aus');
  await turnTo(A); h.emit('test:setPos', A.id, 98, false); await sleep(60); await roll(A, 6); await idle();
  ok(H.S.phase === 'finished' && me(A.id).pos === LAST, 'ohne Exakt-Regel reicht jede Zahl');
  console.log('4) Zeitlimit-Modus mit Exakt-Regel');
  h.emit('host:reset', true); await sleep(100); h.emit('host:settings', { finishExact: true, gameTimeMin: 0.03 }); await sleep(60); h.emit('host:start'); await sleep(100);
  h.emit('test:setPos', A.id, 98, false); h.emit('test:setPos', B.id, 60, false); await sleep(60);
  await turnTo(A); await roll(A, 6); await idle(); ok(me(A.id).pos === 98, 'auch im Zeitlimit-Modus: zu viel = stehen bleiben');
  t1 = Date.now(); while (H.S.phase !== 'finished' && Date.now() - t1 < 6000) await sleep(50);
  ok(H.S.phase === 'finished' && H.S.winner.timeMode && H.S.winner.playerId === A.id, 'Zeit abgelaufen: die Weiteste (Feld 98) gewinnt');
  for (const c of [h, A.c, B.c]) c.close();
  console.log('REGELN-TEST OK'); process.exit(0);
})().catch(e => { console.error(e.message || e); process.exit(1); });
